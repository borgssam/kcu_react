-- 7.2절 ①: tasks 테이블 만들기 + RLS 켜기 + 연습용 데이터 3개 넣기
create table public.tasks (
  id bigint generated by default as identity primary key, -- 1, 2, 3... 자동 증가
  title text not null,                                    -- 할 일 내용(비워 둘 수 없음)
  is_done boolean not null default false,                 -- 완료 여부(기본값 false)
  created_at timestamptz not null default now()           -- 만든 시각(자동)
);

-- RLS(행 수준 보안) 켜기: 이제 정책으로 허락한 동작만 할 수 있다(정책은 ②에서)
alter table public.tasks enable row level security;

insert into public.tasks (title, is_done) values
  ('리액트 공부하기', false),
  ('운동하기', true),
  ('독서하기', false);
